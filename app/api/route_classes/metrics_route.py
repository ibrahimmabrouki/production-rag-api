"""
The first thing we need to understand what is APIRoute in FastAPI:

1- APIRoute is a class in FastAPI that represents a single route in the application. It includes information about the path e.g /chat, the HTTP method e.g POST, the endpoint function that will handle the request, and other metadata about the route.
When we define a route in FastAPI like the following => FastAPI will create an instance of the APIRoute class to represent this route. Then this instance is added to the APIRouter which is a collection of routes. The APIRouter is then included in the main application router.
@router.post("/chat", response_model=ChatResponse)
async def chat(
    body: ChatRequest,
) -> ChatResponse:
    return response

2- APIRouter is a class in FastAPI that represents a collection of routes. It allows you to group related routes together and apply common configurations, such as dependencies, tags, and prefixes. The APIRouter can be included in the main application router to create a modular and organized structure for your API.
APIRouter is mainly a container/registry of routes.

APIRouter
   │
   └── APIRoute
         path = "/chat"
         methods = {"POST"}
         endpoint = chat
         
APIRouter
    = collection of routes

APIRoute
    = object representing ONE route

chat()
    = your endpoint function
    
Example: When a client send an HTTP request: POST /api/chat
- Incoming Request: FastAPI receives the request and starts processing it.
- Router Examines path + method: FastAPI's router examines the request's path and HTTP method to find a matching route.
- Finds the matching APIRoute: The router finds the APIRoute that matches the request.
===> APIRoute for POST /chat which is the object the FastAPI created when we defined the route in the code.


FastAPI internally creates an APIRoute object representing this route. which is /chat.

The APIRoute knows things like:
path       → /chat
method     → POST
handler    → chat()



@router.post("/chat")
async def chat(...):
    return response

chat(): is the route handler function that will be called when a request is made to the /chat endpoint.


when FastAPI finds the matching APIRoute, it will call the get_route_handler() method of the APIRoute class to get the function that will handle this request. This function is called the route handler function.
POST /chat => FastAPI router => matching APIRoute => route handler generated by get_route_handler() => validate request => resolve Depends(...) => call chat() => validate/serialize response => Response

So, In general the APIRoute class is responsible for:
- Matching incoming requests to the correct route based on path and method.
- Getting the route handler function that will process the request.

Then in the route handler function, FastAPI will do the following:
- Validating the request data against the expected input model (e.g., ChatRequest).
- Resolving dependencies (e.g., get_chat_service).
- Calling the route handler function to process the request.

This what happens without the metrics class


3- Now the advantage of the custom class MetricsAPIRoute is that we can override the get_route_handler() method of the APIRoute class to add our own logic which includes the metrics logic. This way we can record metrics for every request that comes to the API.

In general not rebuilding the whole logic, It is just adding additional feature:
- getting the original route handler function and then wrapp it with the updated method metrics_route_handler that will include both our additional logic and the original logic throught the original_route_handler(request) call.

APIRouter => APIRoute => normal route handler
while: 
APIRouter => MetricsAPIRoute => custom route handler with metrics logic

In normal APIRoute, conceptually it does the following: the get_route_handler() method of the APIRoute class: 
def get_route_handler(self):
    return some_fastapi_handler
    
some_fastapi_handler: is the function that will process the request for this route. It will do things like validate the request, resolve dependencies, call the endpoint function, and validate/serialize the response.

what we want to do is to override the get_route_handler() method of the APIRoute class: 
def get_route_handler(self):

    original = FastAPI's handler

    async def my_wrapper(request):
        do_something_before()

        response = await original(request)

        do_something_after()

        return response

    return my_wrapper

In the above code snippet, we are getting the original route handler function from FastAPI, since we need to keep the normal logic
We are wrapping it with our own logic that will do something before and after the original route handler function 

Now we need to build a class that will inherit from APIRoute and we will override the get_route_handler() method of the APIRoute class so that we can add our own logic to it.
original_route_handler = super().get_route_handler() this will give us the function that actually processes the route
so later one we will have response = await original_route_handler(request)

"""


from fastapi.routing import APIRoute
from fastapi import Request, Response


from app.core.monitoring.logging import get_logger
from app.core.monitoring.metrics import metrics


logger = get_logger(__name__)


class MetricsAPIRoute(APIRoute):

    """
    This method already exists in the APIRoute class,  we are just overriding it so that we can add our own logic to it
    FastAPI usually uses this method to build the function that processes the request for the route
    => Build and return the async function that will process an HTTP request for this route.
    """

    def get_route_handler(self):
        """
        This is the most important line in this method
        super() is built into Python which means go to the parent class

        - our class is MetricsAPIRoute which inherits from APIRoute
        - parent class is APIRoute
        - super() is a way to call methods from the parent class
        ===> we are getting the original FastAPI implementation of the get_route_handler() method from the APIRoute class
        -store it in a variable called original_route_handler so that we can call it later on in our own logic.
        "Do everything FastAPI would normally do for this route."
        request => parse body => validate ChatRequest => resolve Depends(get_chat_service) => call chat() => validate ChatResponse => create Response
        """

        original_route_handler = super().get_route_handler()

        """
        Here is the wrapper function that will be returned when a request is made to the route.
        """

        async def metrics_route_handler(
            request: Request,
        ) -> Response:
            """
            The important thing here to understand is that we need the path
            """

            method = request.method

            # Here we already know the route definition because
            # this object represents the actual matched APIRoute.
            endpoint = self.path

            active_request_recorded = False

            # ------------------------------------------------------
            # REQUEST START
            # ------------------------------------------------------

            try:
                metrics.request_started()
                active_request_recorded = True
            except Exception:
                logger.exception(
                    "Failed to record active request start metric"
                )

            try:
                with metrics.track_request_latency(
                    method=method,
                    endpoint=endpoint,
                ):
                    # Execute the real FastAPI route handler.
                    response = await original_route_handler(request)

                    try:
                        metrics.record_request(
                            method=method,
                            endpoint=endpoint,
                            status=response.status_code,
                        )
                    except Exception:
                        logger.exception(
                            "Failed to record request metric"
                        )

                    return response

            except Exception as exc:
                logger.exception(
                    "Exception occurred while processing request using the orginal route handler"
                )
                try:
                    metrics.record_request(
                        method=method,
                        endpoint=endpoint,
                        status=500,
                    )
                except Exception:
                    logger.exception(
                        "Failed to record failed request metric"
                    )

                try:
                    metrics.record_request_error(
                        endpoint=endpoint,
                        error_type=type(exc).__name__,
                    )
                except Exception:
                    logger.exception(
                        "Failed to record request error metric"
                    )

                raise

            finally:

                if active_request_recorded:
                    try:
                        metrics.request_finished()
                    except Exception:
                        logger.exception(
                            "Failed to record active request finish metric"
                        )

        return metrics_route_handler


"""
Notes: 
1- General notes about the Request: 
It is object that represents the incoming HTTP request. It contains information about the request, such as the method (GET, POST, etc.), headers, query parameters, and body. In this code snippet, we are using the Request object to get the method and path of the incoming request.
It doesn't have the route definition or the route_template as a direct property => we can't use request.route_template
But request wraps ASGI scope which is a dictionary that contains information about the request, including the route definition.
This inforamtion the route template is only available after the request has been matched to a route, which is why we are using self.path to get the route definition.


2- why does "route" exist?

suppose that we have a route defined like this:
@router.get("/users/{user_id}")
async def get_user(user_id: int):
    ...
    
Then someone requests GET /users/123

Initially FastAPI only knows raw path = /users/123

The the router compares it against registered routes: 
/users/{user_id}    ← match ✅
/orders/{order_id}  ← no
/chat               ← no

After the match => FastAPI can then associate that route with the request's scope

later: route = request.scope.get("route") can give us the matched APIRoute object
and using route.path we can get the route_template = /users/{user_id} instead of the raw path = /users/123

note the above code doesn't need to use request.scope.get("route) since we are already in the MetricsAPIRoute object that represents the matched route and we can use self.path to get the route_template = /users/{user_id} instead of the raw path = /users/123
Suppose: 
router = APIRouter(
    route_class=MetricsAPIRoute
)

@router.get("/users/{user_id}")
async def get_user(...):
    ...

The metrics object created by FastAPI is: 
MetricsAPIRoute object
    path = "/users/{user_id}"
    methods = {"GET"}
    endpoint = get_user
    
this way we garuntee that track latency will always have general tags associated with the latency histogram and not raw path which will increase the cardinality of the histogram and make it hard to analyze the metrics.
"""
